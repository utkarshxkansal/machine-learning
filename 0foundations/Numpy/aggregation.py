import numpy as np

arr = np.array([1, 2, 3])
print(arr.sum()) # sum of all elements in the array 
print(arr.mean()) # mean of all elements in the array
print(arr.prod()) # product of all elements in the array
print(arr.min()) # minimum value in the array
print(arr.max()) # maximum value in the array
print(arr.std()) # standard deviation of the array
print(arr.var()) # variance of the array